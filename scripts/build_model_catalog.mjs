// Writes web/model-catalog.js, the 模型广场 copy of the model catalog, from server/src/official-models.mjs.
// Run after changing the catalog: node scripts/build_model_catalog.mjs
// server/test/model-catalog.test.mjs fails while the committed file differs from this output.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { marketCatalog } from '../server/src/official-models.mjs';

export const catalogPath = fileURLToPath(new URL('../web/model-catalog.js', import.meta.url));
export const catalogSource = () => `// Generated by scripts/build_model_catalog.mjs from server/src/official-models.mjs. Do not edit by hand.\nwindow.SemiflyModels=${JSON.stringify(marketCatalog(), null, 1)};\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) { await writeFile(catalogPath, catalogSource()); console.log('wrote', catalogPath); }
